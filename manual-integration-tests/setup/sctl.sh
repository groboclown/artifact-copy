#!/bin/sh
#
# Manage one or more of the local test servers.
#
#   ./sctl.sh start nexus
#   ./sctl.sh stop nexus artifactory
#   ./sctl.sh status all
#
# Each named server is a directory beside this script holding a
# `docker-compose.yml`.  Before starting one, this makes sure it has a
# `.env` with generated passwords, so no server in this tree ever comes up
# on a password that is written down in the repository.

set -eu

cd "$(dirname "$0")" || exit 1

# Compose is spelled three ways in the wild, and this tree does not care
# which one is installed.  Resolved once rather than at each call so the
# failure, when there is one, is a single clear message.
compose_cmd() {
    if command -v podman >/dev/null 2>&1 && podman compose version >/dev/null 2>&1 ; then
        echo "podman compose"
    elif command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1 ; then
        echo "docker compose"
    elif command -v podman-compose >/dev/null 2>&1 ; then
        echo "podman-compose"
    elif command -v docker-compose >/dev/null 2>&1 ; then
        echo "docker-compose"
    else
        return 1
    fi
}

# A password safe to put in a `.env` unquoted.
#
# Hex rather than base64: compose expands `$` inside `.env` values and
# splits nothing else, so a base64 password containing `$` would reach the
# server as something other than what was generated - and the symptom is an
# authentication failure nobody connects to the password's alphabet.
generate_password() {
    openssl rand -hex 24
}

# Create `<server>/.env` if it is not already there.
#
# Never regenerated: the passwords are baked into the running server's
# database on first configuration, so rewriting this file would leave the
# file and the server disagreeing.  Delete the file *and* the server's
# volume to rotate them.
ensure_env() {
    server="$1"
    env_file="${server}/.env"

    if [ -f "${env_file}" ]; then
        echo "[start] ${env_file} exists, keeping it"
        return 0
    fi

    if ! command -v openssl >/dev/null 2>&1; then
        >&2 echo "[start] ERROR: openssl is needed to generate ${env_file}"
        return 1
    fi

    echo "[start] generating ${env_file}"

    umask 077

    # The passwords, which every server in this tree needs and which only
    # this script may generate.
    cat > "${env_file}" <<EOF
# Generated by start.sh.  Not for anything real.
#
# These are read by docker compose and handed to the server's configuration
# container, which creates the three users below on first start.
#
# Rotating them means deleting this file AND the server's data volume:
# the passwords live in the server's own database once it is configured.

# Full control of the server.
ADMIN_PASSWORD=$(generate_password)

# Reads and writes artifacts.  What a 'copy' target should authenticate as.
PUBLISH_PASSWORD=$(generate_password)

# Reads and browses only.  What a source or enumerator should authenticate as,
# and the account that proves the tool never needs write access to read.
READONLY_PASSWORD=$(generate_password)
EOF

    # Secrets only this server needs, generated the same way the passwords
    # above were.
    #
    # A script rather than more lines here, because what a server needs is
    # the server's business: Artifact Keeper refuses to start without a
    # strong JWT_SECRET, and neither of the others has such a thing.
    # Optional - a server with nothing extra simply has no such file.
    if [ -f "${server}/env.generate" ]; then
        echo "" >> "${env_file}"

        if ! sh "${server}/env.generate" >> "${env_file}"; then
            >&2 echo "[start] ERROR: ${server}/env.generate failed"
            rm -f "${env_file}"

            return 1
        fi
    fi

    # Whatever else that server wants pre-filled, verbatim.
    #
    # Per server rather than written here, because the answers differ by
    # product: which repository is readable anonymously is `pypi` on Nexus
    # and `maven` on Artifactory, and a single default in this script would
    # be wrong for one of them.  Optional - a server with nothing to add
    # simply has no such file.
    if [ -f "${server}/env.defaults" ]; then
        echo "" >> "${env_file}"
        cat "${server}/env.defaults" >> "${env_file}"
    fi
    chmod 600 "${env_file}"
}

handle_compose() {
    cmd="$1"
    server="$2"
    case "${cmd}" in
        start)
            ensure_env "${server}" || exit 1
            echo "[start] starting ${server}"
            # shellcheck disable=SC2086
            ( cd "${server}" && ${compose} up -d )
            if [ "${server}" = nexus ] ; then
                >&2 echo "WARNING: you must first accept the EULA to publish to this repository, or you must avoid using Nexus.  See ${server}/accept-eula.sh"
            fi
            ;;
        stop)
            echo "[stop] stopping ${server}"
            # shellcheck disable=SC2086
            ( cd "${server}" && ${compose} down )
            ;;
        status)
            echo "[stop] status ${server}"
            ( cd "${server}" && ${compose} ps )
            ;;
        log)
            # Friendly alias for logs.
            echo "[stop] logs ${server}"
            ( cd "${server}" && ${compose} logs )
            ;;
        logs)
            echo "[stop] logs ${server}"
            ( cd "${server}" && ${compose} logs )
            ;;
        watch)
            echo "[stop] watch ${server}"
            ( cd "${server}" && ${compose} logs -f configure )
            ;;
        *)
            >&2 echo "Unknown command: ${cmd}"
            exit 1
            ;;
    esac
}

main() {
    if [ "$#" -eq 0 ] || [ "$1" = "-h" ] || [ "$1" = "--help" ] || [ "$1" = "help" ] ; then
        >&2 echo "Usage: $0 [start|stop|status|logs|watch] <server name> [server name ...]"
        >&2 echo "Available:"

        for dir in */; do
            [ -f "${dir}docker-compose.yml" ] && >&2 echo "  ${dir%/}"
        done

        >&2 echo
        >&2 echo "Or use 'all' to reference all servers."

        exit 1
    fi

    compose="$(compose_cmd)" || {
        >&2 echo "[start] ERROR: no docker compose, docker-compose or podman-compose found"
        exit 1
    }

    cmd="$1"
    shift
    if [ "$#" -eq 0 ] || [ "$1" = "all" ] ; then
        for server in */docker-compose.yml ; do
            handle_compose "${cmd}" "$( basename "$( dirname "${server}" )" )"
        done
        exit 0
    fi
    # Checked before starting anything, so a typo in the third name does not
    # leave the first two running.
    for server in "$@"; do
        if [ ! -f "${server}/docker-compose.yml" ]; then
            >&2 echo "[start] ERROR: no ${server}/docker-compose.yml"
            exit 1
        fi
    done

    for server in "$@"; do
        handle_compose "${cmd}" "${server}"
    done
}

main "$@"
