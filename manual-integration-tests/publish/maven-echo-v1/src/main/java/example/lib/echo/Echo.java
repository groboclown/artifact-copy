package example.lib.echo;

/**
 * Echo text back to the caller.
 */
public class Echo {
    /**
     * Return the passed-in argument back to the caller.
     *
     * @parameter text The text to return.
     * @return The text argument.
     */
    public String echo(final String text) {
        return text;
    }
}
