//! The Maven ecosystem.
//!
//! Two things set Maven's *coordinates* apart, and each is a place a
//! borrowed implementation would go wrong.
//!
//! **A coordinate has more than three parts.** `groupId:artifactId:version`
//! is the common case, but packaging and classifier sit between them, which
//! is how `sources` and `javadoc` jars are addressed.
//!
//! **A `parse_req` failure is the user's typo**, not a repository's fault,
//! so it reports as a bad request rather than as malformed metadata.
//!
//! Version ordering is *not* here: it is
//! [`crate::version::MavenVersions`], because the scheme
//! travels to repositories that are not Maven registries. That is also
//! where the qualifier ranking lives -- Guava ships `31.1-jre` and
//! `31.1-android` as its only releases, so only the five qualifiers Maven
//! itself ranks below a release count as pre-releases.
//!
//! References: [Maven repository metadata](https://maven.apache.org/ref/current/maven-repository-metadata/repository-metadata.html).

use std::sync::Arc;
use std::time::Duration;

use super::Ecosystem;
use crate::core::error::{Error, Result};
use crate::model::{
    ArtifactId, ArtifactRequest, Cause, DepKind, EcosystemId, Provenance, Version, VersionSpec,
};
use crate::version::{MavenVersions, PreRelease, Ranking, VersionHandler};

/// What Maven publishes.
///
/// `dev` stands in for `provided`, which is the closest analogue: present at
/// build time, absent at runtime. `peer` has no Maven meaning at all and is
/// therefore absent, so `--dependencies=peer` against a Maven source is an
/// error rather than an empty result that would read as "there are none".
const DEP_KINDS: [DepKind; 5] = [
    DepKind::Runtime,
    DepKind::Dev,
    DepKind::Test,
    DepKind::Optional,
    DepKind::Build,
];

/// The OSV spelling, which is capitalized differently from the purl type.
const OSV_NAME: &str = "Maven";

/// The repository's index of published versions, and the document name a
/// Maven source caches it under, artifact-level and snapshot alike.
///
/// Read for inspection only: it is never carried as one of an artifact's
/// files.
pub const METADATA_DOCUMENT: &str = "maven-metadata.xml";

/// The document name a version directory's HTML listing is cached under.
pub const LISTING_DOCUMENT: &str = "index.html";

/// Rewritten whenever a version is published, so an hour old at most. A
/// released POM or jar never changes, so neither is named.
const FRESHNESS: [(&str, Duration); 2] = [
    ("maven-metadata.xml*", Duration::from_secs(3_600)),
    (LISTING_DOCUMENT, Duration::from_secs(3_600)),
];

/// The purl qualifier for a packaging type.
pub const TYPE_QUALIFIER: &str = "type";

/// The purl qualifier for a classifier.
pub const CLASSIFIER_QUALIFIER: &str = "classifier";

/// The file a packaging or dependency type publishes, where it is not the
/// type's own name: `(type, extension, classifier)`.
///
/// Maven's artifact handlers, from Maven core, plus the plugins whose
/// packaging is common on Central: `bundle` (Apache Felix
/// maven-bundle-plugin), `eclipse-plugin` (Tycho), and `hk2-jar` (GlassFish
/// HK2). A type not listed publishes under its own name, which is right for
/// `jar`, `war`, `ear`, `rar`, `aar`, and `nbm`.
const HANDLERS: [(&str, &str, Option<&str>); 9] = [
    ("bundle", "jar", None),
    ("maven-plugin", "jar", None),
    ("ejb", "jar", None),
    ("eclipse-plugin", "jar", None),
    ("hk2-jar", "jar", None),
    ("ejb-client", "jar", Some("client")),
    ("test-jar", "jar", Some("tests")),
    ("java-source", "jar", Some("sources")),
    ("javadoc", "jar", Some("javadoc")),
];

/// What a packaging or dependency type publishes: the file extension, and
/// the classifier it implies, if any.
///
/// ```text
///   bundle     ->  jar               foo-1.0.jar
///   test-jar   ->  jar, tests        foo-1.0-tests.jar
///   war        ->  war               foo-1.0.war
/// ```
///
/// A packaging is not an extension: a POM declaring
/// `<packaging>bundle</packaging>` publishes `foo-1.0.jar`, and asking for
/// `foo-1.0.bundle` asks for a file nobody published.
pub fn published_as(packaging: &str) -> (&str, Option<&'static str>) {
    match HANDLERS.iter().find(|(name, _, _)| *name == packaging) {
        Some((_, extension, classifier)) => (extension, *classifier),
        None => (packaging, None),
    }
}

/// Files that belong to the repository rather than to an artifact.
///
/// `maven-metadata.xml` is the version index; see `repo::maven`. `_remote.repositories` is written by Artifactory (and by
/// Maven's own local repository) to record where a file was cached *from*;
/// it describes one machine's cache and means nothing anywhere else.
///
/// Both are regenerated by whatever holds them, so carrying either into a
/// migration would overwrite a target's own truthful state with a claim
/// about a different repository.
const REPOSITORY_MANAGED: [&str; 1] = ["_remote.repositories"];

/// What a snapshot version ends in.
const SNAPSHOT_SUFFIX: &str = "-SNAPSHOT";

/// A snapshot build's timestamp, as Maven writes it: `20240101.123456`.
const SNAPSHOT_TIMESTAMP_FORMAT: &str = "%Y%m%d.%H%M%S";

/// How long [`SNAPSHOT_TIMESTAMP_FORMAT`] renders.
const SNAPSHOT_TIMESTAMP_LEN: usize = 15;

/// Whether a version is a snapshot, which Maven decides by its spelling.
pub fn is_snapshot(version: &str) -> bool {
    version.ends_with(SNAPSHOT_SUFFIX)
}

/// The snapshot version one timestamped build belongs to, or `None` for a
/// version that names no build.
///
/// A catalog such as Nexus lists each build as a version of its own; the
/// repository layout, and every consumer, knows them as one snapshot.
///
/// ```text
///   2.0-20240101.123456-3  -> 2.0-SNAPSHOT
///   2.0-SNAPSHOT           -> None
///   2.0                    -> None
/// ```
pub fn snapshot_of(version: &str) -> Option<String> {
    let (rest, number) = version.rsplit_once('-')?;

    if number.is_empty() || !number.chars().all(|ch| ch.is_ascii_digit()) {
        return None;
    }

    let split = rest.len().checked_sub(SNAPSHOT_TIMESTAMP_LEN)?;
    let (base, timestamp) = rest.split_at_checked(split)?;
    let base = base.strip_suffix('-').filter(|base| !base.is_empty())?;

    chrono::NaiveDateTime::parse_from_str(timestamp, SNAPSHOT_TIMESTAMP_FORMAT).ok()?;

    Some(format!("{base}{SNAPSHOT_SUFFIX}"))
}

/// Whether a file belongs to the repository rather than to an artifact.
pub fn is_repository_file(name: &str) -> bool {
    let base = name.rsplit('/').next().unwrap_or(name);

    // `maven-metadata-central.xml` and `maven-metadata-local.xml` are the
    // same document under a repository-qualified name.
    if base.starts_with("maven-metadata") && base.ends_with(".xml") {
        return true;
    }

    REPOSITORY_MANAGED
        .iter()
        .any(|managed| base.eq_ignore_ascii_case(managed))
}

pub struct Maven;

impl Ecosystem for Maven {
    fn id(&self) -> EcosystemId {
        EcosystemId::new(EcosystemId::MAVEN)
    }

    fn purl_type(&self) -> &str {
        EcosystemId::MAVEN
    }

    fn osv_name(&self) -> &str {
        OSV_NAME
    }

    fn dep_kinds(&self) -> &[DepKind] {
        &DEP_KINDS
    }

    fn freshness(&self) -> &[(&'static str, Duration)] {
        &FRESHNESS
    }

    fn parse_req(&self, text: &str) -> Result<ArtifactRequest> {
        let (id, spec) = parse_coordinate(text)?;

        Ok(ArtifactRequest {
            id,
            spec,
            prov: Arc::new(Provenance::root(Cause::Requested {
                arg: text.to_owned(),
            })),
        })
    }
}

/// Versions are Maven's `ComparableVersion` ordering and its bracketed
/// range syntax.
///
/// Delegated rather than implemented, because the convention is not the
/// ecosystem's property: a raw repository laid out with Maven-style
/// versions configures [`MavenVersions`] directly and gets the same
/// answers.
impl VersionHandler for Maven {
    fn version_spec(&self, text: &str) -> VersionSpec {
        MavenVersions.version_spec(text)
    }

    fn classify(&self, texts: &[String]) -> Vec<Version> {
        MavenVersions.classify(texts)
    }

    fn select(&self, spec: &VersionSpec, of: &[Version], pre: PreRelease) -> Option<Version> {
        MavenVersions.select(spec, of, pre)
    }

    fn compare(&self, a: &Version, b: &Version) -> Ranking {
        MavenVersions.compare(a, b)
    }

    fn sort(&self, versions: &mut [Version]) {
        MavenVersions.sort(versions)
    }
}

/// Split `groupId:artifactId[:packaging[:classifier]]:version`.
///
/// Maven's own coordinate ordering, the one `mvn dependency:get` takes:
/// the version is last, with packaging and classifier between it and the
/// name. Splitting on `:` is safe because a version range uses commas and
/// brackets and never a colon.
fn parse_coordinate(text: &str) -> Result<(ArtifactId, VersionSpec)> {
    let trimmed = text.trim();

    if trimmed.is_empty() {
        return Err(bad(text, "the coordinate is empty"));
    }

    let parts: Vec<&str> = trimmed.split(':').map(str::trim).collect();

    if parts.iter().any(|part| part.is_empty()) {
        return Err(bad(
            text,
            "a coordinate has no empty parts; write group:artifact:version",
        ));
    }

    let (group, artifact) = match parts.as_slice() {
        [group, artifact, ..] => (*group, *artifact),
        _ => {
            return Err(bad(
                text,
                "a coordinate needs at least a group and an artifact, \
                 as group:artifact",
            ));
        }
    };

    let mut id = ArtifactId::new(EcosystemId::maven(), Some(group), artifact);

    let spec = match parts.as_slice() {
        // `g:a` -- any version.
        [_, _] => VersionSpec::Any,

        // `g:a:v`
        [_, _, version] => MavenVersions.version_spec(version),

        // `g:a:packaging:v`
        [_, _, packaging, version] => {
            id = id.with_qualifier(TYPE_QUALIFIER, packaging);
            MavenVersions.version_spec(version)
        }

        // `g:a:packaging:classifier:v`
        [_, _, packaging, classifier, version] => {
            id = id
                .with_qualifier(TYPE_QUALIFIER, packaging)
                .with_qualifier(CLASSIFIER_QUALIFIER, classifier);

            MavenVersions.version_spec(version)
        }

        _ => {
            return Err(bad(
                text,
                "a coordinate has at most five parts: \
                 group:artifact:packaging:classifier:version",
            ));
        }
    };

    Ok((id, spec))
}

fn bad(text: &str, detail: &str) -> Error {
    Error::BadRequest {
        ecosystem: "maven",
        text: text.to_owned(),
        detail: detail.to_owned(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A packaging names how a project is built, and only sometimes the
    /// file it publishes.
    #[test]
    fn packaging_maps_to_published_file() {
        assert_eq!(published_as("bundle"), ("jar", None));
        assert_eq!(published_as("maven-plugin"), ("jar", None));
        assert_eq!(published_as("test-jar"), ("jar", Some("tests")));
        assert_eq!(published_as("java-source"), ("jar", Some("sources")));
        assert_eq!(published_as("war"), ("war", None));
        assert_eq!(published_as("jar"), ("jar", None));
    }

    #[test]
    fn snapshot_of_reads_builds() {
        assert_eq!(
            snapshot_of("2.0-20240101.123456-3").as_deref(),
            Some("2.0-SNAPSHOT")
        );
        assert_eq!(
            snapshot_of("1.0-rc-1-20240101.123456-12").as_deref(),
            Some("1.0-rc-1-SNAPSHOT")
        );
    }

    #[test]
    fn snapshot_of_ignores_non_builds() {
        for version in [
            "2.0-SNAPSHOT",
            "2.0",
            "1.0-rc-1",
            "2.0-20241399.123456-3",
            "20240101.123456-3",
            "2.0-20240101.123456-",
        ] {
            assert_eq!(snapshot_of(version), None, "{version}");
        }
    }

    fn request(text: &str) -> ArtifactRequest {
        Maven
            .parse_req(text)
            .unwrap_or_else(|err| panic!("{text:?} should parse: {err}"))
    }

    fn refused(text: &str) -> String {
        Maven
            .parse_req(text)
            .err()
            .unwrap_or_else(|| panic!("{text:?} should have been refused"))
            .to_string()
    }

    // -- Coordinates ------------------------------------------------------

    #[test]
    fn coordinate_three_parts_names_version() {
        let parsed = request("org.apache.commons:commons-lang3:3.14.0");

        assert_eq!(parsed.id.namespace(), Some("org.apache.commons"));
        assert_eq!(parsed.id.name(), "commons-lang3");
        assert_eq!(parsed.spec, VersionSpec::Exact("3.14.0".into()));
    }

    #[test]
    fn coordinate_two_parts_takes_any_version() {
        let parsed = request("org.apache.commons:commons-lang3");

        assert_eq!(parsed.spec, VersionSpec::Any);
    }

    /// Packaging and classifier sit between the name and the version --
    /// Maven's own ordering, not an afterthought appended at the end.
    #[test]
    fn coordinate_packaging_classifier_into_qualifiers() {
        let parsed = request("org.example:lib:jar:sources:1.2.3");

        assert_eq!(parsed.id.qualifier(TYPE_QUALIFIER), Some("jar"));
        assert_eq!(parsed.id.qualifier(CLASSIFIER_QUALIFIER), Some("sources"));
        assert_eq!(parsed.spec, VersionSpec::Exact("1.2.3".into()));
    }

    #[test]
    fn coordinate_four_parts_packaging_not_classifier() {
        let parsed = request("org.example:lib:pom:1.2.3");

        assert_eq!(parsed.id.qualifier(TYPE_QUALIFIER), Some("pom"));
        assert_eq!(parsed.id.qualifier(CLASSIFIER_QUALIFIER), None);
    }

    /// The identity renders as a purl, which is how both policy files key
    /// artifacts.
    #[test]
    fn coordinate_renders_as_purl() {
        let parsed = request("org.example:lib:jar:sources:1.2.3");

        assert_eq!(
            parsed.id.purl_at("1.2.3"),
            "pkg:maven/org.example/lib@1.2.3?classifier=sources&type=jar"
        );
    }

    #[test]
    fn coordinate_bracketed_version_is_range() {
        assert_eq!(
            request("g:a:[1.0,2.0)").spec,
            VersionSpec::Range("[1.0,2.0)".into())
        );
        assert_eq!(
            request("g:a:(,1.0]").spec,
            VersionSpec::Range("(,1.0]".into())
        );
    }

    #[test]
    fn coordinate_surrounding_whitespace_ignored() {
        let parsed = request("  org.example : lib : 1.0  ");

        assert_eq!(parsed.id.namespace(), Some("org.example"));
        assert_eq!(parsed.id.name(), "lib");
    }

    #[test]
    fn coordinate_too_few_parts_refused() {
        assert!(refused("commons-lang3").contains("group and an artifact"));
    }

    #[test]
    fn coordinate_too_many_parts_refused() {
        assert!(refused("a:b:c:d:e:f").contains("at most five parts"));
    }

    #[test]
    fn coordinate_empty_part_refused() {
        assert!(refused("org.example::1.0").contains("no empty parts"));
        assert!(refused(":lib:1.0").contains("no empty parts"));
        assert!(refused("").contains("empty"));
    }

    // -- Classification ---------------------------------------------------

    #[test]
    fn maven_states_identity_and_osv_name() {
        assert_eq!(Maven.id(), EcosystemId::maven());
        assert_eq!(Maven.purl_type(), "maven");

        // OSV capitalizes it differently, which is exactly why the name is
        // declared rather than derived from the purl type.
        assert_eq!(Maven.osv_name(), "Maven");
    }

    /// `peer` is an npm idea with no Maven meaning, so asking for it must
    /// be an error rather than an empty list.
    #[test]
    fn maven_publishes_no_peer_dependencies() {
        let kinds = Maven.dep_kinds();

        assert!(kinds.contains(&DepKind::Test));
        assert!(kinds.contains(&DepKind::Dev));
        assert!(!kinds.contains(&DepKind::Peer));
    }
}
